/**
 * Removes any remaining English words inside parentheses/brackets, e.g. (Photosynthesis) -> ""
 */
export function removeParenthesizedEnglish(text) {
  if (!text) return "";
  // Strip patterns like (Photosynthesis) or (Preserved Definitions) or [Photosynthesis]
  return text
    .replace(/\s*\([A-Za-z0-9\s,._:;-]+\)/g, "")
    .replace(/\s*\[[A-Za-z0-9\s,._:;-]+\]/g, "")
    .replace(/[ ]{2,}/g, " ")
    .trim();
}

